"""Writes src/kzg_lines.fe: the Miller loop lines of KZG's two fixed G2 points,
-G2 and [tau]G2, as bls_pairing.fe's doubling_step and addition_step give them
over the bits of |x| >> 1. Run from ingots/precompiles:
    python3 gen_kzg_lines.py > src/kzg_lines.fe"""
import re, sys
P = 0x1a0111ea397fe69a4b1ba7b6434bacd764774b84f38512bf6730d2a0f6b0f6241eabfffeb153ffffb9feffffffffaaab
R = pow(2, 384, P); RINV = pow(R, -1, P)
def from_mont(limbs): return sum(l << (64 * i) for i, l in enumerate(limbs)) * RINV % P
def to_mont(x): v = x * R % P; return [(v >> (64 * i)) & (2**64 - 1) for i in range(6)]
class F2:
    def __init__(s, a, b): s.a, s.b = a % P, b % P
    def __add__(s, o): return F2(s.a + o.a, s.b + o.b)
    def __sub__(s, o): return F2(s.a - o.a, s.b - o.b)
    def __mul__(s, o): return F2(s.a * o.a - s.b * o.b, s.a * o.b + s.b * o.a)
    def sq(s): return s * s
    def dbl(s): return s + s
    def neg(s): return F2(-s.a, -s.b)
src = open('src/bls_curve.fe').read() + open('src/kzg_tests.fe').read()
def const(name): return [int(x, 16) for x in re.search(rf'const {name}: \[u64; 6\] = \[([^\]]*)\]', src).group(1).replace(' ', '').split(',')]
def point(prefix): return F2(from_mont(const(prefix + 'X0')), from_mont(const(prefix + 'X1'))), F2(from_mont(const(prefix + 'Y0')), from_mont(const(prefix + 'Y1')))
def doubling(r):
    X, Y, Z = r
    tmp0 = X.sq(); tmp1 = Y.sq(); tmp2 = tmp1.sq()
    tmp3 = ((tmp1 + X).sq() - tmp0 - tmp2).dbl()
    tmp4 = tmp0.dbl() + tmp0; tmp6 = X + tmp4; tmp5 = tmp4.sq(); zz = Z.sq()
    X2 = tmp5 - tmp3 - tmp3
    Z2 = (Z + Y).sq() - tmp1 - zz
    Y2 = (tmp3 - X2) * tmp4 - tmp2.dbl().dbl().dbl()
    c1 = (tmp4 * zz).dbl().neg()
    c2 = tmp6.sq() - tmp0 - tmp5 - tmp1.dbl().dbl()
    c0 = (Z2 * zz).dbl()
    return (X2, Y2, Z2), (c0, c1, c2)
def addition(r, q):
    X, Y, Z = r; qx, qy = q
    zz = Z.sq(); yy = qy.sq(); t0 = zz * qx
    t1 = ((qy + Z).sq() - yy - zz) * zz
    t2 = t0 - X; t3 = t2.sq(); t4 = t3.dbl().dbl(); t5 = t4 * t2
    t6 = t1 - Y - Y; t9 = t6 * qx; t7 = t4 * X
    X2 = t6.sq() - t5 - t7 - t7
    Z2 = (Z + t2).sq() - zz - t3
    t8 = (t7 - X2) * t6
    Y2 = t8 - (Y * t5).dbl()
    t10 = (qy + Z2).sq() - yy - Z2.sq()
    return (X2, Y2, Z2), (Z2.dbl(), t6.neg().dbl(), t9.dbl() - t10)
def lines(q):
    r = (q[0], q[1], F2(1, 0)); out = []; found = False
    X = 0xd201000000010000 >> 1
    for bit in range(63, -1, -1):
        s = (X >> bit) & 1 == 1
        if not found: found = s; continue
        r, l = doubling(r); out.append(l)
        if s: r, l = addition(r, q); out.append(l)
    r, l = doubling(r); out.append(l)
    return out
gx, gy = point('G2_'); tx, ty = point('TAU_G2_')
def emit(name, doc, ls):
    print(f'// {doc}')
    print(f'pub const {name}: [[u64; 6]; {6 * len(ls)}] = [')
    for c0, c1, c2 in ls:
        for f in (c0.a, c0.b, c1.a, c1.b, c2.a, c2.b):
            print('    [' + ', '.join(f'0x{x:016x}' for x in to_mont(f)) + '],')
    print(']')
print('// Generated by ingots/precompiles/gen_kzg_lines.py: the Miller loop\'s')
emit('NEG_G2_LINES', 'lines of -G2, the negated G2 generator', lines((gx, gy.neg())))
emit('TAU_G2_LINES', 'lines of [tau]G2 from the KZG trusted setup', lines((tx, ty)))
